"""Write the SPU assembly for spu_convert_scales: every I8 value for
cflts, cfltu, csflt and cuflt, on four input vectors.

The assembler refuses a scale outside 0..127, so each conversion is
emitted as its instruction word: [SPU-ISA p:220 s:9] RI8 is a 10-bit
opcode, I8 in bits 10:17, RA in 18:24 and RT in 25:31.

Results go to `out` in the order (opcode, I8, input vector), 16 bytes
each; the FPSCR after each csflt and cuflt, cleared before it, goes to
`out` + 65536 in the same order.

Usage: gen_convert.py <out.S>
"""
import sys

OPCODES = [0b0111011000, 0b0111011001, 0b0111011010, 0b0111011011]  # cflts cfltu csflt cuflt
INPUT_REGS = [3, 4, 5, 6]
RT = 10
FPSCR_OUT = 11
ZERO = 12
FPSCR_BASE = 65536

lines = [
    '# Generated by gen_convert.py. Do not edit.',
    '\t.text',
    '\t.align 3',
    '\t.global run_conversions',
    '# Inputs in $3..$6.',
    'run_conversions:',
    '\til $%d,0' % ZERO,
]
result = 0
fpscr = 0
for op_index, op in enumerate(OPCODES):
    sets_flags = op_index >= 2
    for i8 in range(256):
        for ra in INPUT_REGS:
            word = op << 22 | i8 << 14 | ra << 7 | RT
            if sets_flags:
                lines.append('\tfscrwr $%d' % ZERO)
            lines.append('\t.long 0x%08x' % word)
            lines.append('\tstqa $%d,out+%d' % (RT, result))
            result += 16
            if sets_flags:
                lines.append('\tfscrrd $%d' % FPSCR_OUT)
                lines.append('\tstqa $%d,out+%d' % (FPSCR_OUT, FPSCR_BASE + fpscr))
                fpscr += 16
lines.append('\tbi $0')
open(sys.argv[1], 'w', newline='\n').write('\n'.join(lines) + '\n')
