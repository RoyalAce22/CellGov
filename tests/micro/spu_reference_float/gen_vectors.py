"""Generate the spu_reference_float SPU routine from the reference fixtures.

Reads the floating-point units of crates/cellgov_fuzz/tests/fixtures/
spu_reference and selects every vector whose expected registers or FPSCR
are undefined, then appends the EXTRA vectors below. Writes:

  spu/vectors.S  run_vectors: for each vector, write its start FPSCR,
                 zero $2..$10, load its start registers, run its words,
                 read the FPSCR, and store RT then the FPSCR (32 bytes)
                 to results + 32 * index.
  vectors.tsv    index, unit, vector name, RT, words, start registers,
                 start FPSCR: the order the results come back in.

Run from this directory: python3 gen_vectors.py
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
FIXTURES = HERE / '../../../crates/cellgov_fuzz/tests/fixtures/spu_reference'

UNITS = [
    'frest', 'frsqest', 'csflt', 'cflts', 'cuflt', 'cfltu', 'fscrwr', 'fscrrd',
    'dfa', 'dfs', 'dfm', 'dfma', 'dfms', 'dfnms', 'dfnma', 'fesd', 'frds',
]

INF = '7ff00000000000007ff0000000000000'
ZERO = '0' * 32
QNAN = '7ff80000000001237ff8000000000123'
SNAN = '7ff00000000004567ff0000000000456'

# Infinity times zero with a NaN addend in the fused forms: the addend is
# RT, the product RA x RB. Each fused unit's fixture word names RT 3,
# RA 5 and RB 6.
EXTRA = []
for unit in ['dfma', 'dfms', 'dfnms', 'dfnma']:
    for addend, label in [(QNAN, 'qnan'), (SNAN, 'snan')]:
        EXTRA.append((unit, 'inf-times-zero-plus-%s' % label,
                      {'3': addend, '5': INF, '6': ZERO}))

# Registers the routine itself uses; no vector may name them.
SCRATCH = {0, 1, 75, 76, 77}


def undefined(component):
    return isinstance(component, dict) and component.get('status') == 'undefined'


def vectors():
    out = []
    words_of = {}
    for unit in UNITS:
        doc = json.loads((FIXTURES / (unit + '.json')).read_bytes())
        for v in doc['vectors']:
            words_of.setdefault(unit, v['words'])
            e = v['expected']
            if not (undefined(e['regs_hex']) or undefined(e['fpscr'])):
                continue
            init = v['initial_state']
            assert not init.get('local_store'), (unit, v['name'])
            out.append((unit, v['name'], v['words'], init.get('regs_hex', {}),
                        init.get('fpscr') or ZERO))
    for unit, name, regs in EXTRA:
        out.append((unit, name, words_of[unit], regs, ZERO))
    return out


def quad(hex32):
    assert len(hex32) == 32
    return ', '.join('0x' + hex32[i:i + 8] for i in range(0, 32, 8))


def main():
    vs = vectors()
    asm = [
        '/* Generated by gen_vectors.py from the spu_reference fixtures; do not edit. */',
        '\t.text',
        '\t.global\trun_vectors',
        'run_vectors:',
    ]
    data = ['\t.data', '\t.align\t4']
    rows = []
    for i, (unit, name, words, regs, fpscr) in enumerate(vs):
        rt = words[-1] & 0x7F
        assert rt not in SCRATCH, (unit, name, rt)
        for r in regs:
            assert int(r) not in SCRATCH, (unit, name, r)
        asm.append('\t# %d %s %s' % (i, unit, name))
        asm.append('\tlqa\t$75, fpscr_%d' % i)
        asm.append('\tfscrwr\t$0, $75')
        for r in range(2, 11):
            asm.append('\til\t$%d, 0' % r)
        for r in sorted(regs, key=int):
            asm.append('\tlqa\t$%s, reg_%d_%s' % (r, i, r))
        for w in words:
            asm.append('\t.long\t0x%08x' % w)
        asm.append('\tfscrrd\t$76')
        asm.append('\tstqa\t$%d, results + %d' % (rt, 32 * i))
        asm.append('\tstqa\t$76, results + %d' % (32 * i + 16))
        data.append('fpscr_%d:\t.long\t%s' % (i, quad(fpscr)))
        for r in sorted(regs, key=int):
            data.append('reg_%d_%s:\t.long\t%s' % (i, r, quad(regs[r])))
        rows.append('\t'.join([str(i), unit, name, str(rt), ','.join('0x%08x' % w for w in words),
                               ','.join('%s=%s' % (r, regs[r]) for r in sorted(regs, key=int)), fpscr]))
    asm.append('\tbi\t$0')
    data.append('\t.global\tvector_count')
    data.append('vector_count:\t.long\t%d' % len(vs))
    data.append('\t.align\t7')
    data.append('\t.global\tresults')
    data.append('results:\t.space\t%d' % (32 * len(vs)))
    (HERE / 'spu' / 'vectors.S').write_bytes(('\n'.join(asm + [''] + data) + '\n').encode())
    (HERE / 'vectors.tsv').write_bytes(
        ('index\tunit\tname\trt\twords\tregs\tfpscr\n' + '\n'.join(rows) + '\n').encode())
    print('%d vectors' % len(vs))


if __name__ == '__main__':
    main()
